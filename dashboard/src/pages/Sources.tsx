import { useMemo, useState } from 'react';
import { sources, evidence, facilities, products, shortName, statusLevel } from '../data';
import { Card, Badge, Src, PageHead, Legend } from '../ui';

type Tab = 'register' | 'state' | 'products' | 'facilities' | 'method';
const EXPORTS = [
  ['source_register.csv', 'Source register'], ['competitors.csv', 'Competitor research dataset'], ['competitor_comparison_matrix.csv', 'Comparison matrix'],
  ['state_evidence.csv', 'State evidence'], ['states_51.csv', 'State-level dataset (51)'], ['facilities.csv', 'Facilities'], ['thermgas_ci_dataset.json', 'Full dataset (JSON)'],
];

export default function Sources({ params }: { params: URLSearchParams }) {
  const [tab, setTab] = useState<Tab>((params.get('tab') as Tab) || 'register');
  const [q, setQ] = useState('');
  const match = (o: object) => !q || JSON.stringify(o).toLowerCase().includes(q.toLowerCase());
  const types = useMemo(() => [...new Set(sources.map(s => s.type.replace(/\s*\(.*\)/, '')))], []);
  const [type, setType] = useState('all');
  const counts = useMemo(() => {
    const all = [...evidence.map(e => e.status), ...products.map(p => p.dmc_status), ...facilities.map(f => f.status)].map(statusLevel);
    return { Verified: all.filter(x => x === 'Verified').length, Inferred: all.filter(x => x === 'Inferred').length, Unknown: all.filter(x => x === 'Unknown' || x === 'Assumption').length };
  }, []);

  return (
    <div className="stack">
      <PageHead kicker="Sources & Research Methodology" title="Every number traces back to a dated source"
        lead={<>{sources.length} sources, each with publisher, source date and access date. Download the datasets, search the register, or read how competitors were classified.</>} />

      <Card title="Export data" sub="Generated by scripts/build-data.js from the JSON evidence database">
        <div className="toolbar" style={{ marginBottom: 0 }}>
          {EXPORTS.map(([f, l]) => <a key={f} className="btn" href={`./export/${f}`} download>{l} ↓</a>)}
        </div>
      </Card>

      <div className="grid g3">
        <Card title="Evidence confidence" sub="Evidence rows, product DMC claims and facilities">
          <div className="bars">
            {(['Verified', 'Inferred', 'Unknown'] as const).map(k => (
              <div key={k} className="bar-row"><span><Badge status={k} /></span><div className="bar-track"><div className="bar-fill" style={{ width: `${(counts[k] / (counts.Verified + counts.Inferred + counts.Unknown)) * 100}%`, background: k === 'Verified' ? 'var(--ok)' : k === 'Inferred' ? 'var(--warn)' : 'var(--na)' }} /></div><span className="n mono">{counts[k]}</span></div>
            ))}
          </div>
        </Card>
        <Card title="Source mix" sub="By source type">
          <div className="bars">
            {(() => {
              const rows = types.map(t => ({ t, n: sources.filter(s => s.type.startsWith(t)).length })).sort((a, b) => b.n - a.n).slice(0, 7);
              const mx = Math.max(...rows.map(r => r.n));
              return rows.map(x => (
                <div key={x.t} className="bar-row" style={{ gridTemplateColumns: '170px 1fr 30px' }}><span className="small">{x.t}</span><div className="bar-track"><div className="bar-fill" style={{ width: `${x.n / mx * 100}%` }} /></div><span className="n mono">{x.n}</span></div>
              ));
            })()}
          </div>
        </Card>
        <Card title="How to read labels"><Legend /><p className="small" style={{ marginBottom: 0 }}>Vendor specifications are labeled <b>Verified</b> when read in the vendor's own document. That verifies <i>what the vendor claims</i>, not field performance. No laboratory tests were run.</p></Card>
      </div>

      <div className="tabs" role="tablist">
        {([['register', 'Source register'], ['state', 'State evidence'], ['products', 'Product data'], ['facilities', 'Facilities'], ['method', 'Methodology & gaps']] as [Tab, string][]).map(([k, l]) =>
          <button key={k} role="tab" aria-selected={tab === k} className={tab === k ? 'on' : ''} onClick={() => setTab(k)}>{l}</button>)}
      </div>
      {tab !== 'method' && (
        <div className="toolbar">
          <input className="input" placeholder="Search…" value={q} onChange={e => setQ(e.target.value)} aria-label="Search table" />
          {tab === 'register' && <select className="input" value={type} onChange={e => setType(e.target.value)} aria-label="Source type"><option value="all">All types</option>{types.map(t => <option key={t}>{t}</option>)}</select>}
        </div>
      )}

      {tab === 'register' && (
        <div className="table-wrap" style={{ maxHeight: 620 }}>
          <table className="t">
            <thead><tr><th>ID</th><th>Publisher</th><th>Title</th><th>Type</th><th>Source date</th><th>Accessed</th><th>Link</th></tr></thead>
            <tbody>{sources.filter(match).filter(s => type === 'all' || s.type.startsWith(type)).map(s => (
              <tr key={s.id}><td><b>{s.id}</b></td><td>{s.publisher}</td><td>{s.title}</td><td className="small">{s.type}</td><td className="small">{s.source_date}</td><td className="small">{s.access_date}</td><td><a href={s.url} target="_blank" rel="noreferrer">open ↗</a></td></tr>
            ))}</tbody>
          </table>
        </div>
      )}
      {tab === 'state' && (
        <div className="table-wrap" style={{ maxHeight: 620 }}>
          <table className="t">
            <thead><tr><th>Company</th><th>State</th><th>Metric</th><th>Value</th><th>Status</th><th>Source</th><th>Notes</th></tr></thead>
            <tbody>{evidence.filter(match).map((e, i) => (
              <tr key={i}><td>{shortName(e.company)}</td><td><a href={`#/map?s=${e.state}`}>{e.state}</a></td><td>{e.metric}</td><td>{e.value}</td><td><Badge status={e.status} /></td><td><Src ids={[e.source]} label={e.source} /></td><td className="small muted">{e.notes}</td></tr>
            ))}</tbody>
          </table>
        </div>
      )}
      {tab === 'products' && (
        <div className="table-wrap" style={{ maxHeight: 620 }}>
          <table className="t">
            <thead><tr><th>Company</th><th>Product</th><th>Technology</th><th>DMC</th><th>Sensitivity</th><th>Range</th><th>Response</th><th>Maintenance</th><th>Price</th><th>Sources</th></tr></thead>
            <tbody>{products.filter(match).map(p => (
              <tr key={p.id}><td>{shortName(p.company)}</td><td><b>{p.model}</b></td><td>{p.technology}</td><td>{p.dmc_capability}<div><Badge status={p.dmc_status} /></div></td><td>{p.sensitivity}</td><td>{p.range}</td><td>{p.response_time}</td><td>{p.maintenance}</td><td>{p.price}</td><td><Src ids={p.sources} /></td></tr>
            ))}</tbody>
          </table>
        </div>
      )}
      {tab === 'facilities' && (
        <div className="table-wrap" style={{ maxHeight: 620 }}>
          <table className="t">
            <thead><tr><th>Operator</th><th>Location</th><th>Type</th><th>Capacity</th><th>Status (source)</th><th>2025-26 update</th><th>Sources</th></tr></thead>
            <tbody>{facilities.filter(match).map((f, i) => (
              <tr key={i}><td><b>{f.operator}</b></td><td>{f.city}, {f.state}</td><td>{f.type}</td><td className="mono">{f.capacity_gwh ? `${f.capacity_gwh} GWh` : f.capacity_note}</td><td>{f.status_in_source}</td><td>{f.status_update ? <>{f.status_update} <Badge status={f.status_update_status} /></> : <span className="nodata">Not re-verified</span>}</td><td><Src ids={[f.source, f.status_update_source ?? ''].filter(Boolean)} /></td></tr>
            ))}</tbody>
          </table>
        </div>
      )}
      {tab === 'method' && <Method />}
    </div>
  );
}

function Method() {
  return (
    <div className="grid g2">
      <Card title="Methodology">
        <ol style={{ paddingLeft: 18, margin: 0, fontSize: 14 }}>
          <li><b>Understand.</b> Read the class brief, data-analysis plan and ThermGAS website and documents. Brand tokens were read from thermgas.com computed styles.</li>
          <li><b>Discover.</b> Searched vendor sites, catalogs, trade press and government data for products that detect DMC or electrolyte vapor. 18 candidates were screened, 12 kept (incl. ThermGAS) and 6 excluded with reasons.</li>
          <li><b>Classify.</b> <i>Direct</i> = officially marketed for the same continuous DMC/electrolyte-solvent monitoring task in battery production. <i>Indirect</i> = detects DMC or competes for the same budget but measures something else. <i>Substitute</i> = solves the root problem differently (cell leak test, FTIR analysis).</li>
          <li><b>Evidence.</b> One row per fact with company, product, state, metric, value, source, dates, status and notes. Offices, distributors, service, installations and regulatory notes are separate metrics, never summed.</li>
          <li><b>Analyze.</b> Rule-based threat matrix, SWOT, battlecards, and a transparent state-priority model with visible inputs and adjustable weights. No market shares, revenues or TCO were estimated.</li>
          <li><b>Verify.</b> <code>build-data.js</code> fails if any claim cites a missing source ID. Conflicts (ThermGAS 0.5 vs 1 ppm; Li-ion Tamer status) are shown, not resolved by guessing.</li>
        </ol>
      </Card>
      <Card title="Data gaps & limitations">
        <ul style={{ paddingLeft: 18, margin: 0, fontSize: 14 }}>
          <li>No DMC detection limit under matched test conditions for any vendor. Performance is <b>not rankable</b>.</li>
          <li>ThermGAS: 0.5 vs 1 ppm conflict; DMC not on Master Gas List; no interference data; no prices; no battery references.</li>
          <li>Prices: only FALCO 2 11.7 ($3,521) and RAEGuard 2 (from $3,740) are verified public list prices. Chillgard is from a search excerpt. Lamp, labor and ThermGAS prices are unknown.</li>
          <li>Facilities: DOE FCAB list (June 2023 data); 2025-26 updates were checked for 10 plants only. NREL/NAATBatt database was not reachable.</li>
          <li>Distributors: only ION Science publishes a usable U.S. list; RKI and Honeywell channel coverage is largely unverified.</li>
          <li>Absence of evidence in a state means "Not Verified", not "no competition".</li>
          <li>Riken's 10,000-unit and ION's battery claims are vendor statements; no independent validation.</li>
        </ul>
      </Card>
    </div>
  );
}
